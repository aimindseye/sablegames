#!/usr/bin/env python3
"""Writes games/.../TartarusData.kt from docs/tartarus-breach/data (the handoff's JSON). Run from the repo root."""
import json
from pathlib import Path

D = Path("docs/tartarus-breach/data")
OUT = Path("games/src/main/java/org/sableos/games/TartarusData.kt")


def hexc(h):
    return "0xFF" + h.lstrip("#").upper()


def f(x):
    return repr(float(x)) + "f"


def s(x):
    return json.dumps(x)


def main():
    weapons = json.loads((D / "weapons.json").read_text())["weapons"]
    boons = json.loads((D / "boons.json").read_text())["boons"]
    enemies = json.loads((D / "enemies.json").read_text())["enemies"]
    gates = [json.loads(p.read_text()) for p in sorted((D / "gates").glob("gate_*.json"))]
    o = ["// Generated by tools/tartarus/gen_data.py from docs/tartarus-breach/data. Do not edit by hand.",
         "package org.sableos.games", "", "internal object TartarusData {", "    val weapons: List<TbWeapon> =", "        listOf("]
    for w in weapons:
        p = w["projectile"]
        o.append(f'            TbWeapon({s(w["id"])}, {s(w["display_name"])}, {s(w["short_label"])}, {s(w["key_badge"])}, {w["damage_per_shot"]}, '
                 f'{w["fire_rate_ms"]}, {w["favor_cost"]}, TbShot.{ {"hitscan_beam": "BEAM", "wave_arc": "WAVE", "fast_bolt": "BOLT", "chain_lightning": "CHAIN"}[p["type"]] }, '
                 f'{p.get("count", 1)}, {f(p.get("spread_deg", 0))}, {p.get("pierce_count", 0)}, {f(p.get("knockback", 0))}, {hexc(p["color_hex"])}, '
                 f'{f(w["auto_aim_magnetism_deg"])}, {f(p.get("speed_units_sec", 0))}, {p.get("chain_targets", 0)}, {f(p.get("chain_radius_units", 0))}),')
    o += ["        )", "", "    val boons: List<TbBoon> =", "        listOf("]
    for b in boons:
        m = b["modifier"]
        o.append(f'            TbBoon({s(b["id"])}, {s(b["deity"])}, {s(b["display_name"])}, {s(b["description"])}, {hexc(b["accent_hex"])}, '
                 f'{b["max_stacks"]}, {s(m["stat"])}, {f(m["value"])}, {s(m["operation"])}),')
    o += ["        )", "", "    val enemies: List<TbEnemyDef> =", "        listOf("]
    for e in enemies:
        o.append(f'            TbEnemyDef({s(e["id"])}, {s(e["display_name"])}, {s(e["tier"])}, {e["hp"]}, {f(e["speed_units_sec"])}, {s(e["attack_type"])}, '
                 f'{e["damage"]}, {f(e["attack_range_units"])}, {e["obols_drop"]}, {e["favor_drop"]}),')
    o += ["        )", "", "    val gates: List<TbGate> =", "        listOf("]
    for g in gates:
        t = g["theme"]
        o.append(f'            TbGate({s(g["gate_id"])}, {g["gate_number"]}, {s(g["display_name"])}, {hexc(t["skybox_hex"])}, {hexc(t["floor_hex"])}, '
                 f'{hexc(t["pillar_hex"])}, {hexc(t["accent_glow_hex"])}, listOf(')
        for st in g["stages"]:
            boss = st["type"] == "boss"
            pool = st.get("enemy_pool", [])
            mp = (st.get("minion_pool") or [{}])[0]
            o.append(f'                TbStage({st["stage_number"]}, {s(st["title"])}, {str(boss).lower()}, {st.get("duration_sec", 0)}, {f(st["arena_radius"])}, '
                     f'{s(st["pillar_preset"])}, {s(st["hazard"])}, {st.get("spawn_interval_ms", 0)}, {st.get("max_concurrent", 0)}, '
                     f'listOf({", ".join(f"TbPool({s(p["id"])}, {p["weight"]})" for p in pool)}), '
                     f'{s(st.get("boss_id", ""))}, {s(mp.get("id", ""))}, {mp.get("max_concurrent", 0)}, {mp.get("spawn_interval_ms", 0)}),')
        o.append("            )),")
    o += ["        )", "}", ""]
    OUT.write_text("\n".join(o))


if __name__ == "__main__":
    main()
