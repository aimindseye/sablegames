#!/usr/bin/env python3
"""Writes GravelGearsData.kt from the owner's data package (cards.json and the stage files).

Usage: python3 tools/gravelgears/gen_data.py DATA_DIR games/src/main/java/org/sableos/games/GravelGearsData.kt
The game's rules read this table, so the JSON stays the source of truth and the game needs no JSON parser.
"""
import json, sys, os

def main(data, out):
    cards = json.load(open(f"{data}/cards.json"))["cards"]
    manifest = json.load(open(f"{data}/stages/stages_manifest.json"))["stages"]
    L = ["// Generated by tools/gravelgears/gen_data.py from the Gravel & Gears data package. Do not edit by hand.",
         "package org.sableos.games", "", "internal object GravelGearsData {", "    val cards: List<GgCard> ="]
    L.append("        listOf(")
    for c in cards:
        steps = ", ".join(f"GgStep({s['dx']}, {s['dy']}, {str(s['airborne']).lower()})" for s in c["pathSteps"])
        fx = ", ".join(f"GgFx(\"{e['type']}\", {int(e.get('points', e.get('delta', e.get('maxSmash', e.get('count', e.get('durationTurns', e.get('amount', e.get('magnitude', 0))))))))}, {float(e.get('multiplier', 1.0))}f)" for e in c["effects"]) 
        L.append(f"            GgCard(\"{c['id']}\", \"{c['name']}\", \"{c['category']}\", \"{c['rarity']}\", {c.get('starterQty', 0)}, "
                 f"{c['vector']['dx']}, {c['vector']['dy']}, listOf({steps}), listOf({fx}), \"{c['description']}\"),")
    L.append("        )")
    L.append("")
    L.append("    val stages: List<GgStage> =")
    L.append("        listOf(")
    for m in manifest:
        s = json.load(open(f"{data}/stages/{m['file']}"))
        unlock = s["unlocksOnStageGate"]
        L.append(f"            GgStage(\"{s['stageId']}\", \"{s['name']}\", night = {str(s['biomeId'] != 'alpine_topo_day').lower()}, "
                 f"width = {s['trailWidth']}, density = {s['obstacleDensity']}f, mult = {s['scoreMultiplier']}f, "
                 f"endless = {str(s['endlessContinuation']).lower()}, "
                 f"unlockGate = {unlock['gateNumber'] if unlock else 0}, unlockId = \"{unlock['unlockId'] if unlock else ''}\", gates = listOf(")
        for g in s["gates"]:
            obs = ", ".join(f"GgObstacle({o['x']}, {o['y']}, GgKind.{o['type']}, {o.get('spanWidth', 1)})" for o in g["segmentObstacles"])
            filt = ", ".join(f"\"{x}\"" for x in (g["draftPoolFilter"] or []))
            L.append(f"                GgGate({g['gateNumber']}, {g['rowY']}, {g['trailCenterX']}, {g['trailWidth']}, {g['gateSpan']['leftX']}, {g['gateSpan']['rightX']}, "
                     f"\"{g['gateStyle']}\", {g['basePoints']}, {str(g['triggersCardDraft']).lower()}, {str(g['triggersRedrawRecharge']).lower()}, "
                     f"listOf({filt}), listOf({obs})),")
        L.append("            )),")
    L.append("        )")
    L.append("}")
    open(out, "w").write("\n".join(L) + "\n")

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
