#!/usr/bin/env python3
"""Writes GravelGearsData.kt from the owner's data package kept in docs/gravel-gears/data.

Usage (from the repository root): python3 tools/gravelgears/gen_data.py
The game's rules read the generated table, so the JSON stays the source of truth and the game needs no JSON parser.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "docs" / "gravel-gears" / "data"
OUT = ROOT / "games" / "src" / "main" / "java" / "org" / "sableos" / "games" / "GravelGearsData.kt"
EFFECT_KEYS = ("points", "delta", "maxSmash", "count", "durationTurns", "amount", "magnitude")


def number(effect):
    for key in EFFECT_KEYS:
        if key in effect:
            return int(effect[key])
    return 0


def card_line(c):
    steps = ", ".join(f"GgStep({s['dx']}, {s['dy']}, {str(s['airborne']).lower()})" for s in c["pathSteps"])
    fx = ", ".join(f"GgFx(\"{e['type']}\", {number(e)}, {float(e.get('multiplier', 1.0))}f)" for e in c["effects"])
    return (f"            GgCard(\"{c['id']}\", \"{c['name']}\", \"{c['category']}\", \"{c['rarity']}\", {c.get('starterQty', 0)}, "
            f"{c['vector']['dx']}, {c['vector']['dy']}, listOf({steps}), listOf({fx}), \"{c['description']}\"),")


def gate_line(g):
    obs = ", ".join(f"GgObstacle({o['x']}, {o['y']}, GgKind.{o['type']}, {o.get('spanWidth', 1)})" for o in g["segmentObstacles"])
    filt = ", ".join(f"\"{x}\"" for x in (g["draftPoolFilter"] or []))
    return (f"                GgGate({g['gateNumber']}, {g['rowY']}, {g['trailCenterX']}, {g['trailWidth']}, {g['gateSpan']['leftX']}, "
            f"{g['gateSpan']['rightX']}, \"{g['gateStyle']}\", {g['basePoints']}, {str(g['triggersCardDraft']).lower()}, "
            f"{str(g['triggersRedrawRecharge']).lower()}, listOf({filt}), listOf({obs})),")


def stage_lines(s):
    unlock = s["unlocksOnStageGate"]
    head = (f"            GgStage(\"{s['stageId']}\", \"{s['name']}\", night = {str(s['biomeId'] != 'alpine_topo_day').lower()}, "
            f"width = {s['trailWidth']}, density = {s['obstacleDensity']}f, mult = {s['scoreMultiplier']}f, "
            f"endless = {str(s['endlessContinuation']).lower()}, "
            f"unlockGate = {unlock['gateNumber'] if unlock else 0}, unlockId = \"{unlock['unlockId'] if unlock else ''}\", gates = listOf(")
    return [head, *[gate_line(g) for g in s["gates"]], "            )),"]


def main():
    cards = json.loads((DATA / "cards.json").read_text())["cards"]
    manifest = json.loads((DATA / "stages" / "stages_manifest.json").read_text())["stages"]
    lines = [
        "// Generated by tools/gravelgears/gen_data.py from docs/gravel-gears/data. Do not edit by hand.",
        "package org.sableos.games",
        "",
        "internal object GravelGearsData {",
        "    val cards: List<GgCard> =",
        "        listOf(",
        *[card_line(c) for c in cards],
        "        )",
        "",
        "    val stages: List<GgStage> =",
        "        listOf(",
    ]
    for m in manifest:
        stage = json.loads((DATA / "stages" / Path(m["file"]).name).read_text())
        lines += stage_lines(stage)
    lines += ["        )", "}"]
    OUT.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
